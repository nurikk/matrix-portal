struct RetroCanvas {
  uint16_t pixels[kRetroCanvasSize * kRetroCanvasSize] = {};

  void clear(uint16_t color = kBlack) {
    for (uint16_t &pixel : pixels) pixel = color;
  }
  void pixel(int x, int y, uint16_t color) {
    if (x >= 0 && x < kRetroCanvasSize && y >= 0 && y < kRetroCanvasSize)
      pixels[y * kRetroCanvasSize + x] = color;
  }
  void rect(int x, int y, int w, int h, uint16_t color) {
    for (int dy = 0; dy < h; ++dy)
      for (int dx = 0; dx < w; ++dx) pixel(x + dx, y + dy, color);
  }
  template <unsigned H, unsigned W, unsigned N>
  void sprite(int x, int y, const char (&rows)[H][W], const uint16_t (&palette)[N],
              bool flip = false) {
    for (unsigned dy = 0; dy < H; ++dy) {
      for (unsigned dx = 0; dx < W - 1; ++dx) {
        char value = rows[dy][dx];
        if (value == '.') continue;
        uint8_t color = value <= '9' ? value - '0' : value - 'A' + 10;
        if (color < N) {
          uint16_t spriteColor = palette[color];
          pixel(x + (flip ? W - 2 - dx : dx), y + dy,
                spriteColor == kBlack ? kSpriteBlack : spriteColor);
        }
      }
    }
  }
  uint16_t panelPixel(uint8_t x, uint8_t y, uint8_t width, uint8_t height) const {
    uint16_t size = width < height ? width : height;
    int px = x - (width - size) / 2;
    int py = y - (height - size) / 2;
    if (px < 0 || py < 0 || px >= size || py >= size) return kBlack;
    return pixels[(py * kRetroCanvasSize / size) * kRetroCanvasSize +
                  px * kRetroCanvasSize / size];
  }
};

