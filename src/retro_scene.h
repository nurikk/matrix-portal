constexpr uint16_t kPinkyPalette[] = {0, 0xFDDF, 0xDEFF, 0x211F};
constexpr uint16_t kInkyPalette[] = {0, 0x07FF, 0xDEFF, 0x211F};
constexpr uint16_t kClydePalette[] = {0, 0xFDCA, 0xDEFF, 0x211F};
constexpr uint16_t kFrightenedFlashPalette[] = {0, 0xDEFF, 0xF800};
constexpr uint8_t kPingPongFrame[] = {0, 1, 2, 1};

inline void renderRetroScene(RetroCanvas &canvas, RetroScene scene, uint32_t elapsedMs) {
  uint32_t t = elapsedMs < kRetroSceneDurationMs ? elapsedMs : kRetroSceneDurationMs - 1;
  canvas.clear();
  switch (scene) {
  case RetroScene::Mario: {
    canvas.rect(0, 56, 64, 2, kMarioBlockPalette[2]);
    canvas.rect(0, 58, 64, 6, kMarioBlockPalette[1]);
    for (int x = 0; x < 64; x += 8) {
      canvas.rect(x, 58, 1, 6, kMarioBlockPalette[4]);
      canvas.rect(x, 61, 8, 1, kMarioBlockPalette[4]);
    }
    int bump = t >= 2800 && t < 3100 ? 2 : 0;
    uint8_t blockFrame = t < 2800 ? (t / 125) % 3 : 3;
    canvas.sprite(28, 16 - bump, kMarioBlock[blockFrame], kMarioBlockPalette);
    int x = t < 2100 ? 2 + t * 23 / 2100 : t < 3800 ? 25 : 25 + (t - 3800) * 22 / 3200;
    int jump = 0;
    if (t >= 2100 && t < 3500) {
      int u = t - 2100;
      jump = 4 * 11 * u * (1400 - u) / (1400 * 1400);
    }
    if (t >= 2100 && t < 3500)
      canvas.sprite(x, 40 - jump, kMarioPose[1], kMarioPalette);
    else if (t < 2100 || t >= 3800)
      canvas.sprite(x, 40, kMarioWalk[(t / 100) % 3], kMarioWalkPalette);
    else
      canvas.sprite(x, 40, kMarioPose[0], kMarioPalette);
    if (t >= 2800 && t < 4300) {
      int u = t - 2800;
      int rise = 4 * 12 * u * (1500 - u) / (1500 * 1500);
      canvas.sprite(28, 4 - rise, kMarioCoin[(t / 100) % 3], kMarioCoinPalette);
    }
    break;
  }
  case RetroScene::PacMan: {
    canvas.rect(0, 19, 64, 1, kPacMazeHighlight);
    canvas.rect(0, 20, 64, 1, kPacMazeBlue);
    canvas.rect(0, 42, 64, 1, kPacMazeBlue);
    canvas.rect(0, 43, 64, 1, kPacMazeHighlight);
    bool powered = t >= 3000;
    int pacX = powered ? 51 - (t - 3000) * 15 / 4000 : 47 + t * 4 / 3000;
    if (!powered) {
      for (int x = pacX + 14; x < 58; x += 5) canvas.pixel(x, 31, kPacDot);
      canvas.rect(59, 29, 4, 4, kPacDot);
    }
    uint8_t pacFrame = kPingPongFrame[(t / kPacManFrameMs) % 4];
    canvas.sprite(pacX, 25, kPacManLeft[pacFrame], kPacManPalette, !powered);
    uint8_t ghostFrame = powered ? (t / 66) % 2 : (t / 132) % 2;
    for (uint8_t i = 0; i < 4; ++i) {
      int gx = pacX - 14 - i * 13;
      if (powered) {
        if (t >= 6000 && ((t / 264) & 1))
          canvas.sprite(gx, 25, kFrightenedGhost[ghostFrame], kFrightenedFlashPalette);
        else
          canvas.sprite(gx, 25, kFrightenedGhost[ghostFrame], kFrightenedPalette);
      } else {
        switch (i) {
        case 0: canvas.sprite(gx, 25, kGhostLeft[ghostFrame], kGhostPalette, true); break;
        case 1: canvas.sprite(gx, 25, kGhostLeft[ghostFrame], kPinkyPalette, true); break;
        case 2: canvas.sprite(gx, 25, kGhostLeft[ghostFrame], kInkyPalette, true); break;
        default: canvas.sprite(gx, 25, kGhostLeft[ghostFrame], kClydePalette, true); break;
        }
      }
    }
    break;
  }
  case RetroScene::Kirby: {
    uint32_t leg = t % 2240;
    bool movingRight = leg < 1120;
    uint16_t distance = movingRight ? leg : leg - 1120;
    int x = movingRight ? 8 + distance * 28 / 1120 : 36 - distance * 28 / 1120;
    canvas.sprite(x, 34, kKirbyWalk[kPingPongFrame[(t / 170) % 4]], kKirbyPalette, !movingRight);
    canvas.sprite(2, 10 + ((t / 170) & 1), kKirbyStar[0], kKirbyStarPalette);
    canvas.sprite(46, 15 - ((t / 170) & 1), kKirbyStar[0], kKirbyStarPalette, true);
    canvas.sprite(24, 2, kKirbyStar[0], kKirbyStarPalette);
    canvas.rect(10, 53, 44, 1, kKirbyStage);
    break;
  }
  case RetroScene::MegaMan: {
    canvas.rect(0, 55, 64, 2, kMegaGroundHighlight);
    canvas.rect(0, 57, 64, 7, kMegaGround);
    for (int x = 0; x < 64; x += 8) canvas.rect(x, 59, 6, 2, kBlack);
    int x = t < 1700 ? 7 : t < 3700 ? 7 + (t - 1700) * 20 / 2000 : 27;
    if (t < 500) {
      canvas.sprite(7, -32 + t * 55 / 500, kMegaManTeleport[0], kMegaManTeleportPalette);
    } else if (t < 650) {
      canvas.sprite(7, 23, kMegaManTeleport[2], kMegaManTeleportPalette);
    } else if (t >= 3900 && t < 6000) {
      canvas.sprite(x, 31, kMegaManShoot[kPingPongFrame[(t / 117) % 4]],
                    kMegaManShootPalette, true);
      uint16_t bulletElapsed = (t - 3900) % 350;
      int px = x + 30 + bulletElapsed * 20 / 350;
      canvas.rect(px, 41, 3, 3, kMegaManPalette[2]);
      canvas.pixel(px + 1, 42, kMegaManPalette[3]);
    } else {
      uint8_t walkFrame = t >= 1700 && t < 3700
          ? kPingPongFrame[((t - 1700) / 117) % 4]
          : 0;
      canvas.sprite(x, 31, kMegaManWalk[walkFrame], kMegaManPalette, true);
    }
    break;
  }
  case RetroScene::DuckHunt: {
    if (t < 4200) {
      int x = -24 + t * 96 / 4200;
      int y = 23 - t * 14 / 4200;
      canvas.sprite(x, y, kDuckFly[(t / 180) % 3], kDuckPalette);
    }
    if (t >= 4400) {
      int rise = t < 5200 ? (t - 4400) * 40 / 800 : 40;
      canvas.sprite(18, 57 - rise, kDogLaugh[(t / 100) % 2], kDogPalette);
    }
    canvas.rect(0, 57, 64, 7, kDuckSoil);
    for (int x = 0; x < 64; x += 3) {
      canvas.rect(x, 54 + x % 3, 1, 7, kDuckGrass);
      canvas.pixel(x + 1, 56, kDuckGrass);
    }
    break;
  }
  case RetroScene::Count: break;
  }
}
